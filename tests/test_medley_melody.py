def digest(path: Path) -> str:
    """Pin synthetic physical bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fixture(root: Path, *, frames: int = 300) -> tuple[Path, Path, Path, Path]:
    """Generate clearly synthetic coordinates and schema objects, never upstream facts."""
    raw = root / "raw-input"
    raw.mkdir()
    ids = ["Synthetic_Alpha", "Synthetic_Beta", "Synthetic_Missing"]
    pilot = {
        "revision": "medley-melody2-native-contour-pilot-v1",
        "source_repository": "https://github.com/marl/medleydb",
        "source_commit": "0" * 40,
        "synthetic_contract_fixture_not_upstream": True,
        "caps": melody.CAPS,
        "contract": melody.CONTRACT,
        "nominated_native_track_ids": ids,
        "rights": {
            "license": "CC BY-NC-SA4.0",
            "license_url": "https://creativecommons.org/licenses/by-nc-sa/4.0/",
            "local_research_only": True,
            "public_code_and_synthetic_fixtures_only": True,
            "publish_raw_derived_annotations_or_real_results": False,
            "attribution": "Synthetic fixture generated by this test; not a source capture",
            "source_notice": "https://medleydb.weebly.com/downloads.html",
        },
    }
    p = root / "pilot-input.json"
    p.write_bytes(melody.encoded(pilot))
    rows, before, total = [], [], 0
    for index, native in enumerate(ids[:2]):
        # Constant test tones are not copied or transcribed musical material.
        data = "".join(f"{i * 256 / 44100!r},{440 + 440 * index}\n" for i in range(frames)).encode()
        (raw / (native + "_MELODY2.csv")).write_bytes(data)
        row = {
            "native_track_id": native,
            "status": "usable",
            "size": len(data),
            "bytes": len(data),
            "path": melody.PREFIX + native + "_MELODY2.csv",
            "sha": hashlib.sha1(
                b"blob " + str(len(data)).encode() + b"\0" + data, usedforsecurity=False
            ).hexdigest(),
            "sha256": hashlib.sha256(data).hexdigest(),
            "frames": frames,
            "voiced_frames": frames,
            "max_grid_error_seconds": 0.0,
        }
        rows.append(row)
        before.append(
            {k: v for k, v in row.items() if k in ("native_track_id", "size", "path", "sha")}
        )
        before[-1]["status"] = "nominated_for_capture"
        total += len(data)
    missing = {"native_track_id": ids[-1], "status": "missing"}
    rows.append(missing)
    before.append(missing)
    preflight = root / "preflight-input.json"
    preflight.write_bytes(
        melody.encoded(
            {
                "pilot_sha256": digest(p),
                "nomination_outcomes": before,
                "allocated_annotation_bytes": total,
            }
        )
    )
    census = root / "census-input.json"
    census.write_bytes(
        melody.encoded(
            {
                "pilot_sha256": digest(p),
                "preflight_sha256": digest(preflight),
                "source_commit": pilot["source_commit"],
                "nominations": rows,
                "total_raw_bytes": total,
                "total_usable_frames": frames * 2,
                "captures": 2,
            }
        )
    )
    return raw, p, preflight, census


def build(root: Path, output: Path) -> tuple[str, tuple[Path, Path, Path, Path]]:
    """Build the same strict closed artifact from explicitly synthetic inputs."""
    raw, p, preflight, census = fixture(root)
    pin = melody.build_source(
        raw, p, digest(p), preflight, digest(preflight), census, digest(census), output
    )
    return pin, (raw, p, preflight, census)


class MelodySearchTests(unittest.TestCase):
    """Independent direct arithmetic and strict offline source/query boundaries."""

    @override
    def setUp(self) -> None:
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        self.pack = self.root / "pack"
        self.pin, self.inputs = build(self.root, self.pack)
        self.source = melody.load_source(self.pack, self.pin)
        self.query = {
            "times_seconds": (np.arange(173) * melody.HOP + 12).tolist(),
            "f0_hz": [440.0] * 173,
        }

    def reseal(self) -> str:
        body = json.loads((self.pack / "manifest.json").read_bytes())
        body["files"] = melody._inventory(self.pack)
        (self.pack / "manifest.json").write_bytes(melody.encoded(body))
        return digest(self.pack / "manifest.json")

    def test_new_caller_input_changes_alignment_and_retains_all_outcomes(self) -> None:
        first = melody.search_contour(self.source, self.query)
        self.assertEqual(first["results"][0]["native_track_id"], "Synthetic_Alpha")
        self.assertEqual(first["results"][0]["start_frame"], 0)
        self.assertEqual(first["results"][0]["distance_ticks"], 0)
        second = melody.search_contour(self.source, {**self.query, "f0_hz": [880.0] * 173})
        self.assertEqual(second["results"][0]["native_track_id"], "Synthetic_Beta")
        self.assertEqual(len(second["nominations"]), 3)
        self.assertEqual(second["nominations"][-1]["status"], "source_unavailable")
        self.assertEqual(first["rights"], self.source.pilot["rights"])
        self.assertEqual(first["source_manifest_sha256"], self.pin)

    def test_independent_direct_window_costs_ticks_and_alignment(self) -> None:
        rng = np.random.default_rng(123)
        hz = rng.choice([0.0, 220.0, 440.0, 660.0], 390)
        q = rng.choice([0.0, 220.0, 440.0], 173)
        a = melody.contour(np.arange(len(hz)) * melody.HOP, hz, query=False)
        b = melody.contour(np.arange(len(q)) * melody.HOP, q, query=True)
        expected = []
        for start in range(len(hz) - len(q) + 1):
            costs, overlap = [], 0
            for x, y in zip(hz[start : start + len(q)], q, strict=True):
                if x > 0 and y > 0:
                    overlap += 1
                    costs.append((12 * (math.log2(float(x)) - math.log2(float(y)))) ** 2)
                else:
                    costs.append(144.0 if (x > 0) != (y > 0) else 0.0)
            if overlap * 4 >= int((q > 0).sum()) * 3:
                cost = math.fsum(costs) / len(q)
                expected.append((round(cost / melody.TICK), start, cost))
        match = melody._best(a, b)
        self.assertIsNotNone(match)
        assert match is not None
        want = min(expected)
        self.assertEqual((match["distance_ticks"], match["start_frame"]), want[:2])
        self.assertAlmostEqual(match["mean_squared_midi_distance"], want[2], places=11)

    def test_voice_gates_and_all_frame_denominator(self) -> None:
        q = [440.0] * 44 + [0.0] * 129
        b = melody.contour(np.arange(173) * melody.HOP, q, query=True)
        for joint in (32, 33):
            a = melody.contour(
                np.arange(173) * melody.HOP, [440.0] * joint + [0.0] * (173 - joint), query=False
            )
            result = melody._best(a, b)
            if joint == 32:
                self.assertIsNone(result)
            else:
                assert result is not None
                self.assertEqual(result["distance_ticks"], round((11 * 144 / 173) / melody.TICK))
        unsupported = melody.search_contour(
            self.source, {**self.query, "f0_hz": [440.0] * 43 + [0.0] * 130}
        )
        self.assertEqual(unsupported["status"], "query_insufficient_voicing")
        self.assertEqual(unsupported["results"], [])

    def test_no_input_mutation_subnormal_and_quantized_tie(self) -> None:
        times = np.arange(173) * melody.HOP
        hz = np.full(173, np.nextafter(0.0, 1.0))
        b = melody.contour(times, hz, query=True)
        self.assertTrue(times.flags.writeable and hz.flags.writeable)
        self.assertTrue(np.isfinite(b.midi).all())
        own = melody._best(b, b)
        assert own is not None
        self.assertEqual(own["distance_ticks"], 0)
        a = melody.contour(np.arange(300) * melody.HOP, [440.0] * 300, query=False)
        match = melody._best(a, melody.contour(times, [440.0] * 173, query=True))
        assert match is not None
        self.assertEqual(match["start_frame"], 0)
        tiny = 440 * 2 ** (math.sqrt(4e-9) / 12)
        tied = melody.contour(
            np.arange(346) * melody.HOP, [tiny] * 173 + [440.0] * 173, query=False
        )
        exact = melody.contour(times, [440.0] * 173, query=True)
        found = melody._best(tied, exact)
        assert found is not None
        self.assertEqual((found["distance_ticks"], found["start_frame"]), (0, 0))
        self.assertGreater(found["mean_squared_midi_distance"], 0)
        arrays = {
            "times_seconds": np.asarray(self.query["times_seconds"]),
            "f0_hz": np.asarray(self.query["f0_hz"]),
        }
        self.assertEqual(
            melody.search_contour(self.source, arrays),
            melody.search_contour(self.source, self.query),
        )
        self.assertTrue(arrays["times_seconds"].flags.writeable)
        self.assertTrue(arrays["f0_hz"].flags.writeable)

    def test_query_schema_grid_finite_values_and_caps(self) -> None:
        variants = [[], [0.0] * 173, [float("nan")] * 173]
        for values in variants:
            with self.assertRaises(ValueError):
                melody.contour(values, [440.0] * len(values), query=True)
        for value in (True, "440", -1, 20001, float("inf")):
            q = copy.deepcopy(self.query)
            q["f0_hz"][0] = value  # ty: ignore[invalid-assignment] -- Deliberately invalid caller values.
            with self.assertRaises(ValueError):
                melody.search_contour(self.source, q)
        for request in ({**self.query, "artist": "forbidden"}, {"f0_hz": []}):
            with self.assertRaises(ValueError):
                melody.search_contour(self.source, request)
        with self.assertRaises(ValueError):
            melody.search_contour(self.source, self.query, limit=True)
        with self.assertRaises(ValueError):
            melody._json(b'{"a":1,"a":2}')
        with self.assertRaises(ValueError):
            melody._json(b'{"a":NaN}')

    def test_inventory_hash_symlink_nested_manifest_and_binding_types(self) -> None:
        with self.assertRaises(ValueError):
            melody.load_source(self.pack, "0" * 64)
        extra = self.pack / "raw/manifest.json"
        extra.write_text("{}")
        with self.assertRaises(ValueError):
            melody.load_source(self.pack, self.reseal())
        extra.unlink()
        body = json.loads((self.pack / "manifest.json").read_bytes())
        body["files"] = melody._inventory(self.pack)
        body["files"]["pilot.json"]["bytes"] = float(body["files"]["pilot.json"]["bytes"])
        (self.pack / "manifest.json").write_bytes(melody.encoded(body))
        with self.assertRaisesRegex(ValueError, "binding"):
            melody.load_source(self.pack, digest(self.pack / "manifest.json"))
        self.reseal()
        link = self.root / "linked"
        link.symlink_to(self.pack, target_is_directory=True)
        with self.assertRaises(ValueError):
            melody.load_source(link, digest(self.pack / "manifest.json"))

    def test_resealed_bad_grid_blob_rights_and_runtime(self) -> None:
        for name, mutate in (
            ("runtime", lambda body: body["runtime"].update({"numpy": "wrong"})),
            ("rights", lambda body: body["rights"].update({"local_research_only": False})),
        ):
            path = self.pack / ("manifest.json" if name == "runtime" else "pilot.json")
            original = path.read_bytes()
            body = json.loads(original)
            mutate(body)
            path.write_bytes(melody.encoded(body))
            with self.assertRaises(ValueError):
                melody.load_source(self.pack, digest(self.pack / "manifest.json"))
            path.write_bytes(original)
        bad = self.root / "bad.csv"
        for content in (b"# comment\n0,440\n", b"0,440,1\n", b"0,440\n0,440\n", b"1,440\n"):
            bad.write_bytes(content)
            with self.assertRaises(ValueError):
                melody._csv(content)
        raw, p, pre, census = self.inputs
        (raw / "Synthetic_Alpha_MELODY2.csv").write_text("0,440\n")
        output = self.root / "failed-build"
        with self.assertRaises(ValueError):
            melody.build_source(raw, p, digest(p), pre, digest(pre), census, digest(census), output)
        self.assertFalse(output.exists())
        self.assertEqual(list(self.root.glob(".melody-*")), [])

    def test_source_build_is_fresh_and_allocation_cannot_be_relabelled(self) -> None:
        raw, p, pre, census = self.inputs
        with self.assertRaises(ValueError):
            melody.build_source(
                raw, p, digest(p), pre, digest(pre), census, digest(census), self.pack
            )
        body = json.loads(pre.read_bytes())
        body["nomination_outcomes"][0]["status"] = "not_attempted_total_cap"
        pre.write_bytes(melody.encoded(body))
        c = json.loads(census.read_bytes())
        c["preflight_sha256"] = digest(pre)
        census.write_bytes(melody.encoded(c))
        with self.assertRaisesRegex(ValueError, "allocation"):
            melody.build_source(
                raw,
                p,
                digest(p),
                pre,
                digest(pre),
                census,
                digest(census),
                self.root / "bad-allocation",
            )

    def test_chunked_working_arrays_and_cli_new_query(self) -> None:
        calls = []
        square = np.square

        def bounded(values: np.ndarray) -> np.ndarray:
            calls.append(values.shape)
            return square(values)

        with patch.object(melody.np, "square", side_effect=bounded):
            melody.search_contour(self.source, self.query)
        self.assertTrue(calls)
        self.assertTrue(all(shape[0] <= melody.CHUNK and shape[1] == 173 for shape in calls))
        query = self.root / "query.json"
        query.write_bytes(melody.encoded(self.query))
        output = self.root / "result.json"
        command = [
            sys.executable,
            str(ROOT / "scripts/query_melody_contour.py"),
            "query",
            "--source",
            str(self.pack),
            "--source-sha256",
            self.pin,
            "--query",
            str(query),
            "--query-sha256",
            digest(query),
            "--output",
            str(output),
        ]
        done = subprocess.run(command, capture_output=True, text=True, check=True)  # noqa: S603
        self.assertEqual(json.loads(done.stdout)["result_sha256"], digest(output))
        self.assertEqual(
            json.loads(output.read_bytes())["results"][0]["native_track_id"], "Synthetic_Alpha"
        )
        self.assertNotEqual(subprocess.run(command, capture_output=True, check=False).returncode, 0)  # noqa: S603
