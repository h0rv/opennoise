import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path
from typing import override
from unittest.mock import patch

import numpy as np
from scipy import sparse

from opennoise.ml import fma_nonlinear_experiment as experiment
from opennoise.ml.fma_component_balanced import Corpus
from opennoise.pipeline import fma_backend as backend


class BackendTest(unittest.TestCase):
    @override
    def setUp(self) -> None:
        self.validate_repo = backend.validate_repo
        validation = patch.object(backend, "validate_repo")
        validation.start()
        self.addCleanup(validation.stop)
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.inputs = self.root / "inputs"
        self.repo = self.root / "repo"
        self.output = self.root / "run"
        self.inputs.mkdir()
        for name in ("source", "native"):
            (self.inputs / name).mkdir()
            (self.inputs / name / "data").write_text("fixture")
        for name in ("declaration", "protocol"):
            (self.inputs / name).write_text("{}")
        (self.repo / "src").mkdir(parents=True)
        (self.repo / "src" / "fixture.py").write_text("# synthetic\n")
        (self.repo / "scripts").mkdir()
        for name in (
            "project_fma_native_bank.py",
            "run_fma_fixed_nonlinear.py",
            "run_fma_backend.py",
        ):
            (self.repo / "scripts" / name).write_text("print('synthetic child')\n")
        self.pin = backend.prepare(
            self.inputs,
            self.repo,
            self.output,
            {key: key for key in ("source", "native", "declaration", "protocol")},
        )

    def test_wrong_checkout_cannot_supply_in_process_validators(self) -> None:
        with self.assertRaisesRegex(ValueError, "selected repository"):
            self.validate_repo(self.repo)
        actual = Path(backend.__file__).resolve().parents[3]
        self.validate_repo(actual)
        with (
            patch.object(experiment, "__file__", str(self.repo / "wrong.py")),
            self.assertRaisesRegex(ValueError, "stage validator"),
        ):
            self.validate_repo(actual)

    def test_generated_caches_do_not_change_code_pin(self) -> None:
        before = backend.code_inventory(self.repo)
        cache = self.repo / "src/__pycache__"
        cache.mkdir()
        (cache / "fixture.pyc").write_bytes(b"generated bytecode")
        self.assertEqual(backend.code_inventory(self.repo), before)
        (self.repo / "src/fixture.py").write_text("# changed executable")
        self.assertNotEqual(backend.code_inventory(self.repo), before)

    def test_order_and_initial_readiness(self) -> None:
        self.assertEqual(len(backend.stages()), 43)
        self.assertEqual(backend.stages()[2:6], [f"fit-0-{arm}" for arm in backend.ARMS])
        self.assertEqual(
            backend.verify(self.output, self.inputs, self.pin)["next_stage"], "project"
        )
        args, limit = backend.command(
            "project",
            self.repo,
            self.inputs,
            self.output,
            json.loads((self.output / "pipeline.json").read_text()),
        )
        self.assertEqual(limit, 360)
        self.assertIn("--declaration-sha256", args)

    def test_resume_skips_completed_and_requires_external_pin(self) -> None:
        with patch.object(backend, "validate_stage") as validator:
            first = backend.run(self.output, self.inputs, self.repo, self.pin, max_stages=1)
            self.assertEqual(validator.call_count, 1)
            with self.assertRaises(ValueError):
                backend.run(self.output, self.inputs, self.repo, self.pin, max_stages=1)
            second = backend.run(
                self.output,
                self.inputs,
                self.repo,
                self.pin,
                first["checkpoint_sha256"],
                max_stages=1,
            )
            self.assertEqual(second["completed"], ["project", "freeze"])
            self.assertEqual(validator.call_count, 2)
        (self.output / "checkpoint-01.json").write_text("{}")
        with self.assertRaises(ValueError):
            backend.verify(self.output, self.inputs, self.pin, second["checkpoint_sha256"])

    def test_relocation_verifies_but_cannot_resume(self) -> None:
        with patch.object(backend, "validate_stage"):
            result = backend.run(self.output, self.inputs, self.repo, self.pin, max_stages=1)
        moved_inputs, moved_output = self.root / "moved-inputs", self.root / "moved-run"
        shutil.copytree(self.inputs, moved_inputs)
        shutil.copytree(self.output, moved_output)
        self.assertEqual(
            backend.verify(moved_output, moved_inputs, self.pin, result["checkpoint_sha256"])[
                "completed"
            ],
            ["project"],
        )
        with self.assertRaisesRegex(ValueError, "Relocated"):
            backend.run(
                moved_output, moved_inputs, self.repo, self.pin, result["checkpoint_sha256"]
            )

    def test_partial_and_changed_inputs_fail_closed(self) -> None:
        with (
            patch.object(backend, "validate_stage", side_effect=ValueError("bad receipt")),
            self.assertRaisesRegex(ValueError, "bad receipt"),
        ):
            backend.run(self.output, self.inputs, self.repo, self.pin, max_stages=1)
        with self.assertRaisesRegex(ValueError, "partial"):
            backend.verify(self.output, self.inputs, self.pin)
        (self.inputs / "source/data").write_text("tampered")
        with self.assertRaisesRegex(ValueError, "inputs changed"):
            backend.verify(self.output, self.inputs, self.pin)

    def test_links_and_role_escape_rejected(self) -> None:
        (self.inputs / "link").symlink_to(self.inputs / "protocol")
        with self.assertRaisesRegex(ValueError, "Links"):
            backend.inventory(self.inputs)
        with self.assertRaisesRegex(ValueError, "within"):
            backend.prepare(
                self.inputs,
                self.repo,
                self.root / "bad",
                {
                    "source": "../source",
                    "native": "native",
                    "protocol": "protocol",
                    "declaration": "declaration",
                },
            )

    def test_explicit_bank_reuse_is_bound_to_declaration_and_source(self) -> None:
        shutil.rmtree(self.output)
        bank = self.inputs / "bank"
        bank.mkdir()
        native_receipt = self.inputs / "native/source-receipt.json"
        native_receipt.write_text("{}")
        declaration = {"source_receipt_sha256": backend.digest(native_receipt)}
        (self.inputs / "declaration").write_text(json.dumps(declaration))
        (bank / "bank-declaration.json").write_text(json.dumps(declaration))
        roles = {key: key for key in ("source", "native", "declaration", "protocol", "bank")}
        pin = backend.prepare(self.inputs, self.repo, self.output, roles)
        with (
            patch(
                "opennoise.ingest.fma_native_bank.verify_native_bank", return_value={}
            ) as checked,
            patch.object(backend, "execute") as launched,
        ):
            result = backend.run(self.output, self.inputs, self.repo, pin, max_stages=1)
        self.assertEqual(result["completed"], ["project"])
        checked.assert_called_once_with(bank)
        launched.assert_not_called()
        shutil.rmtree(self.output)
        (bank / "bank-declaration.json").write_text("{}")
        pin = backend.prepare(self.inputs, self.repo, self.output, roles)
        with self.assertRaisesRegex(ValueError, "selected declaration"):
            backend.run(self.output, self.inputs, self.repo, pin, max_stages=1)

    def test_full_synthetic_lifecycle_uses_real_stage_receipts(self) -> None:
        rng = np.random.default_rng(9)
        x = rng.normal(size=(60, 4))
        full = np.column_stack([x, x**2])
        groups = np.arange(60) // 3
        targets = sparse.csr_matrix(
            np.column_stack([np.arange(60) % 2 == 0, np.arange(60) % 3 == 0])
        )
        corpus = Corpus(np.arange(1, 61), groups, groups % 5, x, targets, (1, 2), groups, groups)

        def synthetic_child(
            args: list[str], _repo: Path, _env: dict[str, str], log: Path, _timeout: int
        ) -> int:
            log.write_text("synthetic stage\n")
            if "project_fma_native_bank.py" in args[1]:
                return 0
            phase = args[2]
            seal = self.output / "model-seal.json"
            run = self.output / "experiment"
            if phase == "freeze":
                seal.write_text("{}")
            elif phase == "summary":
                experiment.summarize(seal, run)
            else:
                fold = int(args[args.index("--fold") + 1])
                arm = args[args.index("--arm") + 1]
                function = experiment.fit_stage if phase == "fit" else experiment.score_stage
                function(seal, run, fold, arm)
            return 0

        with (
            patch.object(backend, "execute", side_effect=synthetic_child),
            patch("opennoise.ingest.fma_native_bank.verify_native_bank", return_value={}),
            patch.object(experiment, "load_inputs", return_value=(corpus, full)),
            patch.object(
                experiment,
                "verify_seal",
                return_value={"protocol": {"interpretation": ["synthetic, not retained outcomes"]}},
            ),
        ):
            result = backend.run(self.output, self.inputs, self.repo, self.pin)
        self.assertTrue(result["ready"])
        self.assertEqual(len(result["completed"]), 43)
        self.assertTrue(
            backend.verify(self.output, self.inputs, self.pin, result["checkpoint_sha256"])["ready"]
        )
        report = json.loads((self.output / "experiment/summary/results.json").read_text())
        for arm in backend.ARMS:
            self.assertEqual(report["arms"][arm]["all"]["totals"]["queries"], 60)

    def test_bounded_child_logs_and_timeout(self) -> None:
        with self.assertRaisesRegex(ValueError, "log exceeds"):
            backend.execute(
                [sys.executable, "-c", "print('x'*1000001)"],
                self.repo,
                {},
                self.root / "large.log",
                5,
            )
        self.assertLessEqual((self.root / "large.log").stat().st_size, backend.LOG_LIMIT)
        with self.assertRaises(TimeoutError):
            backend.execute(
                [sys.executable, "-c", "import time;time.sleep(5)"],
                self.repo,
                {},
                self.root / "timeout.log",
                1,
            )


if __name__ == "__main__":
    unittest.main()
